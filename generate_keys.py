#!/usr/bin/env python3
"""
generate_keys.py - Generates secure cryptographic keys for MoodMate.
Run this script to initialize your .env file or generate new keys.
"""

import os
import secrets
import base64

def generate_fernet_key() -> str:
    # 32 url-safe base64 bytes
    return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()

def generate_secret_token(nbytes: int = 32) -> str:
    return secrets.token_hex(nbytes)

def main():
    fernet_key = generate_fernet_key()
    email_pepper = generate_secret_token(32)
    jwt_secret = generate_secret_token(32)

    print("=" * 60)
    print(" MoodMate - Cryptographic Keys Generator")
    print("=" * 60)
    print(f"FERNET_KEY={fernet_key}")
    print(f"EMAIL_PEPPER={email_pepper}")
    print(f"JWT_SECRET={jwt_secret}")
    print("=" * 60)

    env_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env")
    env_example_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env.example")

    if not os.path.exists(env_path):
        content = f"""# MoodMate Environment Configuration
# Auto-generated by generate_keys.py

# Cryptographic Keys (Do NOT share or commit!)
FERNET_KEY={fernet_key}
EMAIL_PEPPER={email_pepper}
JWT_SECRET={jwt_secret}
JWT_ALGORITHM=HS256
JWT_EXPIRATION_MINUTES=1440

# LLM Providers (Free Tiers - Optional)
OLLAMA_BASE_URL=http://localhost:11434/v1
DEFAULT_MODEL=ollama/llama3.2
ALLOW_USER_KEYS=true

# Optional Free API Keys (Leave blank if using Ollama only)
GEMINI_API_KEY=
GROQ_API_KEY=
OPENROUTER_API_KEY=
YOUTUBE_API_KEY=

# Storage
EXCEL_DB_PATH=moodmate_data.xlsx

# Security & Limits
RATE_LIMIT=60/minute
"""
        with open(env_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"Created '{env_path}' with fresh keys.")
    else:
        print(f"'{env_path}' already exists. Keys were NOT overwritten.")
        print("To replace them, edit your .env manually using the values printed above.")

if __name__ == "__main__":
    main()

